@pytest.fixture
def b3dm_glb_json_4mod8(tmp_path: Path) -> Path:
    """Bug #4 trigger: GLB JSON chunk length is 4 mod 8 (= the residue
    where align4 and align8 give DIFFERENT answers). Real-world example:
    the failing task's ``Tile_13.b3dm`` has json_chunk_len=1348 (mod4=0,
    mod8=4). Pre-fix the code used ``_align8(1348)=1352`` and located
    the BIN chunk 4 bytes too late; the chunk-header read at the wrong
    offset returned "second GLB chunk is not BIN"."""
    # Default gltf JSON is 294 bytes; add 2 trailing spaces to make 296.
    # 296 % 8 = 0, useless. Add 6 more bytes → 302 → mod4=2, mod8=6 (also
    # useless, align4=304, align8=304). Add 4 more → 306 → mod4=2, mod8=2.
    # Easier: just use a length where we KNOW align4 ≠ align8. 304 mod8=0
    # → useless. We want mod8 in {4, 6}. Easiest: 300 mod8=4, mod4=0.
    p = tmp_path / "glb_4mod8.b3dm"
    p.write_bytes(_build_b3dm(
        ftj=0, ftb=0, btj=0, btb=0,
        vertex_count=100,
        extra_glb_json_bytes=6,   # 294 + 6 = 300, mod4=0, mod8=4
    ))
    return p


