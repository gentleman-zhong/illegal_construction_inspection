# ── BUG #5: Draco detection ──────────────────────────────────────

def test_draco_gltf_raises_unsupported_extension_error(b3dm_draco_gltf: Path):
    """Bug #5 / Limitation: every b3dm in the failing task's A tileset
    declares ``KHR_draco_mesh_compression`` (POSITION accessors have no
    ``bufferView`` — Draco replaces the standard lookup chain).

    ``read_accessor`` must detect this case explicitly via
    ``extensionsUsed`` and raise ``UnsupportedExtensionError`` with an
    actionable message. Pre-fix, the missing ``bufferView`` key caused
    a cryptic ``KeyError: 'bufferView'`` deep in the parse pipeline —
    operators had no way to know to install a Draco decoder.
    """
    from point_cloud_extraction import (
        parse_b3dm, read_accessor, UnsupportedExtensionError,
    )
    b = parse_b3dm(b3dm_draco_gltf)
    pos_idx = b.gltf["meshes"][0]["primitives"][0]["attributes"]["POSITION"]
    with pytest.raises(UnsupportedExtensionError) as excinfo:
        read_accessor(b.gltf, b.bin_payload, pos_idx)
    # The error message should be self-explanatory: it must name the
    # extension and say it's not supported. Without these keywords an
    # operator looking at logs wouldn't know what to do.
    msg = str(excinfo.value)
    assert "KHR_draco_mesh_compression" in msg, (
        f"error message does not name the Draco extension: {msg!r}"
    )
    assert "Draco" in msg, (
        f"error message does not mention the 'Draco' keyword: {msg!r}"
    )
    # The exception must subclass RuntimeError so existing
    # ``except RuntimeError`` handlers keep working.
    assert isinstance(excinfo.value, RuntimeError), (
        "UnsupportedExtensionError must subclass RuntimeError"
    )


def test_accessor_without_buffer_view_raises_unsupported(b3dm_draco_gltf: Path):
    """A defensive guard: even without ``extensionsUsed`` declaring
    Draco, an accessor with no ``bufferView`` key must not crash with
    a raw ``KeyError``. The error should still be the actionable
    ``UnsupportedExtensionError`` (the most likely cause is a
    non-standard compressed accessor layout)."""
    from point_cloud_extraction import parse_b3dm
    # Load the b3dm, then strip extensionsUsed so we hit the second
    # code path (the bufferView-less branch).
    b = parse_b3dm(b3dm_draco_gltf)
