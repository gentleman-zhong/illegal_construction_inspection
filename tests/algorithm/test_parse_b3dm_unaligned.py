"""Regression tests for v0.8.2 fix — ``parse_b3dm`` and ``_b3dm_position_count``
must accept b3dm files whose feature/batch table JSON lengths are NOT 8-byte
aligned, AND must locate the embedded GLB correctly even when the FT/BT
binary sections are non-empty.

Background: a 2026-08-11 production task (``20260811153934A331BD``) failed
because the base tileset was generated by a tool that writes
``{"BATCH_LENGTH":2}`` (20 bytes) into the feature table — which, after
8-byte alignment, leaves 4 bytes of trailing zero padding. The original
``parse_b3dm`` sliced ``data[cursor:ftj_end]`` (the *aligned* offset, NOT
the raw ``ftj`` bytes) and the trailing padding triggered
``JSONDecodeError: Extra data: line 1 column 21 (char 20)``. Likewise,
``_b3dm_position_count`` had a copy-paste typo on ``btb_end`` that used
``_align8(btj)`` instead of ``_align8(btb)``, so when ``btb != btj`` the
GLB magic check fired.

These tests pin 7 distinct layouts to catch every regression class:

1. Non-aligned ``ftj`` (the failing-task case).
2. Non-aligned ``btj`` only.
3. Both ``ftj`` and ``btj`` non-aligned (typical real-world case).
4. Non-empty ``ftb`` with non-aligned ``ftj`` (binary section between
   two padded JSON sections — stresses the slice logic).
5. Non-empty ``btb`` with non-aligned ``btj``.
6. Legacy empty FT/BT (``ftj=btj=ftb=btb=0``).
7. The exact case from the failing task (ftj=20, ftb=0, btj=44, btb=0).

Run::

    python -m pytest tests/algorithm/test_parse_b3dm_unaligned.py -v
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent
                      / "scripts" / "algorithm"))


def _build_b3dm(
    ftj: int,
    ftb: int,
    btj: int,
    btb: int,
    ft_payload: bytes = b"",
    ftb_payload: bytes = b"",
    bt_payload: bytes = b"",
    btb_payload: bytes = b"",
    vertex_count: int = 100,
    *,
    pad_sections: bool = True,
    extra_glb_json_bytes: int = 0,
) -> bytes:
    """Pack a minimal-but-valid b3dm with caller-controlled FT/BT layout.

    The FT JSON and BT JSON sections are padded to 8-byte alignment
    per b3dm 1.0 spec — but the JSON itself is ``ftj`` / ``btj`` bytes
    long, with the trailing bytes being zero padding that the JSON
    parser MUST NOT see.
    """
    # ---- Embedded glTF (POSITION-only) ----
    gltf = {
        "asset": {"version": "2.0"},
        "meshes": [{
            "primitives": [{
                "attributes": {"POSITION": 0},
                "mode": 4,
            }],
        }],
        "accessors": [{
            "count": vertex_count,
            "componentType": 5126,
            "type": "VEC3",
            "bufferView": 0,
        }],
        "bufferViews": [{
            "buffer": 0,
            "byteOffset": 0,
            "byteLength": vertex_count * 12,
        }],
        "buffers": [{
            "byteLength": vertex_count * 12,
        }],
    }
    json_bytes = json.dumps(gltf).encode("utf-8")
    # Pad the GLB JSON chunk to a specific residue mod 8 so we can test
    # the 4-vs-8 byte alignment requirement for the BIN chunk offset.
    # Default 294-byte gltf JSON is 4n+2, where align4 and align8 happen
    # to agree — not useful for regression testing. Use extra bytes to
    # force json_chunk_len mod 8 = 4 (the bug-triggering residue).
    if extra_glb_json_bytes:
        json_bytes = json_bytes + b" " * extra_glb_json_bytes
    bin_data = b"\x00" * (vertex_count * 12)
    # GLB chunks use 4-byte alignment per the glTF 2.0 spec (§ 4.2).
    # Use 4-byte padding here so the BIN chunk actually lives at
    # ``glb_off + 20 + align4(json_chunk_len)`` (where align4 != align8
    # for the bug-triggering residue mod 8 = 4).
    json_padded_len = ((len(json_bytes) + 3) // 4) * 4
    bin_padded_len = ((len(bin_data) + 3) // 4) * 4

    glb_header = struct.pack(
        "<4sII", b"glTF", 2,
        12 + 8 + json_padded_len + 8 + bin_padded_len,
    )
    json_chunk_header = struct.pack("<I4s", len(json_bytes), b"JSON")
    json_padding = b"\x00" * (json_padded_len - len(json_bytes))
    bin_chunk_header = struct.pack("<I4s", len(bin_data), b"BIN\x00")
    bin_padding = b"\x00" * (bin_padded_len - len(bin_data))
    glb_body = (glb_header + json_chunk_header + json_bytes + json_padding
                + bin_chunk_header + bin_data + bin_padding)

    # ---- FT/BT section padding ----
    # When ``pad_sections=False``, sections run back-to-back at their raw
    # byte lengths (some non-spec 3D-Tiles generators skip the padding —
    # see e.g. task ``20260811153934A331BD``).
    def _p(n: int) -> int:
        if not pad_sections or n == 0:
            return n
        return ((n + 7) // 8) * 8
    ftj_padding = b"\x00" * (_p(ftj) - ftj)
    ftb_padding = b"\x00" * (_p(ftb) - ftb)
    btj_padding = b"\x00" * (_p(btj) - btj)
    btb_padding = b"\x00" * (_p(btb) - btb)

    b3dm_body = (ft_payload + ftj_padding + ftb_payload + ftb_padding
                 + bt_payload + btj_padding + btb_payload + btb_padding
                 + glb_body)

    # 28-byte b3dm header
    header = struct.pack(
        "<4sIIIIII",
        b"b3dm", 1,
        28 + len(b3dm_body),
        ftj, ftb, btj, btb,
    )
    return header + b3dm_body


